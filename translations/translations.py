def translate(locale: str, text: str) -> str:
    """根据语言和原文查找翻译

    Args:
        locale: "zh_TW" / "en_US" / "zh_CN"
        text: 中文原文

    Returns:
        翻译后的文字。如果找不到翻译则返回原文。
    """
    if locale == "zh_CN":
        return text
    d = {"zh_TW": zh_TW, "en_US": en_US}.get(locale, {})
    return d.get(text, text)
